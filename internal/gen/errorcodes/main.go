// Command errorcodes generates errors.go at the module root from the
// pinned spec's registries/error-codes.md. Run it with `go generate ./...`
// from the module root; the package's test fails when errors.go is stale.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

const (
	registryPath = "testdata/spec/registries/error-codes.md"
	outputPath   = "errors.go"
)

func main() {
	md, err := os.ReadFile(registryPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	src, err := Generate(md)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(outputPath, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type code struct {
	name      string
	status    string // core | draft
	retryable string // "true", "false" or "" when no table states it
}

func cells(line string) []string {
	line = strings.TrimSpace(line)
	line = strings.TrimPrefix(line, "|")
	line = strings.TrimSuffix(line, "|")
	out := strings.Split(line, "|")
	for i := range out {
		out[i] = strings.TrimSpace(out[i])
	}
	return out
}

// Parse reads every registry table whose header starts with "Code" and has
// a spec_status column. A code listed in several tables must agree on its
// status and, where both state it, on retryability.
func Parse(md []byte) ([]code, error) {
	byName := map[string]*code{}
	codeCol, statusCol, retryCol := -1, -1, -1
	inTable := false
	for _, line := range strings.Split(string(md), "\n") {
		if !strings.HasPrefix(strings.TrimSpace(line), "|") {
			inTable = false
			continue
		}
		c := cells(line)
		if !inTable {
			inTable = true
			codeCol, statusCol, retryCol = -1, -1, -1
			for i, h := range c {
				switch h {
				case "Code":
					codeCol = i
				case "spec_status":
					statusCol = i
				case "Retryable":
					retryCol = i
				}
			}
			continue
		}
		if codeCol != 0 || statusCol < 0 || strings.HasPrefix(c[0], "---") {
			continue
		}
		if len(c) <= statusCol || !strings.HasPrefix(c[0], "`") || !strings.HasSuffix(c[0], "`") {
			return nil, fmt.Errorf("unexpected registry row: %s", line)
		}
		name := strings.Trim(c[0], "`")
		for _, r := range name {
			if !(r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_') {
				return nil, fmt.Errorf("invalid code name %q", name)
			}
		}
		status := c[statusCol]
		if status != "core" && status != "draft" {
			return nil, fmt.Errorf("%s: spec_status %q", name, status)
		}
		retry := ""
		if retryCol >= 0 {
			retry = c[retryCol]
			if retry != "true" && retry != "false" {
				return nil, fmt.Errorf("%s: retryable %q", name, retry)
			}
		}
		if prev, ok := byName[name]; ok {
			if prev.status != status {
				return nil, fmt.Errorf("%s: spec_status %q and %q", name, prev.status, status)
			}
			if retry != "" && prev.retryable != "" && retry != prev.retryable {
				return nil, fmt.Errorf("%s: retryable %q and %q", name, prev.retryable, retry)
			}
			if prev.retryable == "" {
				prev.retryable = retry
			}
			continue
		}
		byName[name] = &code{name: name, status: status, retryable: retry}
	}
	if len(byName) == 0 {
		return nil, fmt.Errorf("no codes found")
	}
	out := make([]code, 0, len(byName))
	for _, c := range byName {
		out = append(out, *c)
	}
	slices.SortFunc(out, func(a, b code) int { return strings.Compare(a.name, b.name) })
	return out, nil
}

func goName(code string) string {
	var b strings.Builder
	b.WriteString("Code")
	for _, part := range strings.Split(code, "_") {
		if part == "" {
			continue
		}
		b.WriteString(part[:1])
		b.WriteString(strings.ToLower(part[1:]))
	}
	return b.String()
}

// Generate returns the gofmt'd errors.go for the registry text md.
func Generate(md []byte) ([]byte, error) {
	codes, err := Parse(md)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen/errorcodes from " + registryPath + "; DO NOT EDIT.\n\n")
	b.WriteString("package aitpverifier\n\n")
	b.WriteString("// ErrorCode is an AITP error code from the spec's error-code registry.\n")
	b.WriteString("type ErrorCode string\n\n")
	b.WriteString("// The registered error codes.\nconst (\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "\t%s ErrorCode = %q\n", goName(c.name), c.name)
	}
	b.WriteString(")\n\n")
	b.WriteString("// CodeInfo is a code's registry metadata.\ntype CodeInfo struct {\n")
	b.WriteString("\t// Draft is true for codes reserved to the opt-in draft RFCs.\n\tDraft bool\n")
	b.WriteString("\t// Retryable is the registry's retryability; RetryableStated is false\n\t// when no registry table states it for the code.\n")
	b.WriteString("\tRetryable       bool\n\tRetryableStated bool\n}\n\n")
	b.WriteString("var codeInfo = map[ErrorCode]CodeInfo{\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "\t%s: {Draft: %t, Retryable: %t, RetryableStated: %t},\n",
			goName(c.name), c.status == "draft", c.retryable == "true", c.retryable != "")
	}
	b.WriteString("}\n\n")
	b.WriteString("// Info returns the registry metadata of c; ok is false for an unregistered code.\n")
	b.WriteString("func (c ErrorCode) Info() (info CodeInfo, ok bool) {\n\tinfo, ok = codeInfo[c]\n\treturn info, ok\n}\n")
	return format.Source(b.Bytes())
}
